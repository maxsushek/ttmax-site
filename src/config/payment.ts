/**
 * ⚠️ ОНЛАЙН-ОПЛАТА ТИМЧАСОВО ВИМКНЕНА (рішення власника, 04.08.2026).
 *
 * ЧОМУ ЦЕ НЕ ПРОСТО «ще не підключили», а виправлення зламаного сценарію:
 * форма чекауту збирала номер картки, термін і CVV, валідувала їх — і НЕ відправляла нікуди.
 * У /api/orders летить лише `payment.method`; жодного платіжного шлюзу в проєкті немає.
 * Тобто покупець вводив картку, бачив «Замовлення оформлено» і був упевнений, що заплатив,
 * а гроші не списувались. Магазин при цьому отримував замовлення, схоже на оплачене.
 *
 * Поки шлюзу немає, лишаємо тільки те, що справді працює:
 *   • накладений платіж (оплата при отриманні в перевізника);
 *   • оплата при самовивозі в магазині.
 *
 * ЯК УВІМКНУТИ НАЗАД, коли зʼявиться шлюз:
 *   1. поставити ONLINE_PAYMENT_ENABLED = true;
 *   2. під'єднати реальний платіжний провайдер — інакше повернеться та сама пастка,
 *      бо поля картки досі нікуди не надсилаються (див. CheckoutForm, гілка form.payment === "card");
 *   3. оновити текст на /payment (src/data/info.ts, розділ payment) — він мусить збігатися
 *      з тим, що реально є на чекауті;
 *   4. звірити CSP у next.config.ts: із живими полями картки коментар про веб-скімінг
 *      знову стає актуальним.
 */
export const ONLINE_PAYMENT_ENABLED = false;

/** Усі способи оплати, які вміє чекаут. Порядок — як показуємо користувачу. */
export const PAYMENT_METHODS = ["cod", "apple", "card"] as const;
export type PaymentMethod = (typeof PAYMENT_METHODS)[number];

/** Способи, які онлайн-оплата вимикає. */
const ONLINE_METHODS: readonly PaymentMethod[] = ["apple", "card"];

/** Доступні зараз способи оплати. Єдине джерело і для UI, і для валідації в /api/orders. */
export const AVAILABLE_PAYMENT_METHODS: readonly PaymentMethod[] = ONLINE_PAYMENT_ENABLED
  ? PAYMENT_METHODS
  : PAYMENT_METHODS.filter((m) => !ONLINE_METHODS.includes(m));

/** Спосіб за замовчуванням — завжди перший з доступних. */
export const DEFAULT_PAYMENT_METHOD: PaymentMethod = AVAILABLE_PAYMENT_METHODS[0] ?? "cod";
