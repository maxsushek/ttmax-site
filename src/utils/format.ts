/**
 * ⚠️ «грн», а НЕ знак ₴ — і повертати ₴ не треба.
 *
 * Заміряно на живому проді через PageSpeed: один символ ₴ робив кандидатами ТРИ
 * підмножинні файли вебшрифта, яких немає серед префетчених, — Tektur latin-ext
 * (16 КБ), Roboto latin-ext (25 КБ) і Roboto cyrillic-ext (32 КБ), разом 73 КБ.
 * Вони висіли в критичному ланцюжку й забивали канал у момент відмальовки.
 * «грн» — кирилиця, вона вже завантажена, тож коштує рівно нуль.
 *
 * Рішення власника 04.08.2026. Форма «грн» — стандарт для українського рітейлу.
 */
export const CURRENCY_SYMBOL = "грн";

export function formatPrice(amount: number): string {
  return `${new Intl.NumberFormat("uk-UA").format(amount)}\u00A0${CURRENCY_SYMBOL}`;
}

/**
 * Номер телефону в полі вводу: «+380 67 123 45 67», хоч би як його набирали.
 *
 * ⚠️ НАВІЩО переписано (23.11.2026). Поле показує підказку «+380 …» і цифрову клавіатуру,
 * тож номер природно набирають із 380. Стара версія дописувала «380» до всього, що не
 * починалось із «380» чи «0», вже на першій цифрі:
 *   • «3» → «+380 3», «38» → «+380 38», і далі номер ставав «+380 38 050 12 34» — помилка
 *     перевірки на номері, який людина набрала правильно;
 *   • стерти поле було неможливо: «+38» знову ставало «+380 38» — і так по колу.
 * Обидва випадки — на першому кроці оформлення й у «Швидкому замовленні».
 *
 * Тепер: «3» і «38» — це ще не дописаний код країни (нічого не додаємо); перед номером
 * відкидаємо зайвий «0» («+380 050…»), повторений код країни й старий префікс «8» («8 050…»).
 * Перевірено посимвольним набором і стиранням для: 0501234567, 501234567, 380501234567,
 * +380501234567, 80501234567, вставки «+38 (050) 123-45-67»; іноземні номери («+7 701…»,
 * «8 916…») українськими не стають.
 */
export function formatPhone(raw: string): string {
  const digits = raw.replace(/\D/g, "");
  if (!digits) return "";
  // Код країни набирають цифра за цифрою (або стирають): чекаємо, не дописуючи «380».
  if (digits === "3" || digits === "38") return `+${digits}`;
  // «3» і далі не 8 і не 9 — залишок стертого коду країни («+3» + «0 67…»): кодів операторів
  // 30–37 не буває, тож ця трійка — не початок номера.
  if (/^3[0-7]$/.test(digits)) return formatPhone(digits.slice(1));
  // Знімаємо все, що не є самим номером, доки є що знімати: нулі спереду («0 50 …», «00 380 …»,
  // «+380 050 …»), код країни (зокрема набраний удруге, коли в полі вже стоїть «+380»),
  // зіпсований код країни «38» без нуля і «8» старого запису «8 050 …» — лише перед нулем:
  // «8 916 …» чи «8 777 …» — це чужі номери, а не український запис.
  let national = digits;
  let uaPrefix = false;
  for (;;) {
    const before = national;
    national = national.replace(/^0+/, "");
    if (national.startsWith("380")) national = national.slice(3);
    else if (national.startsWith("38")) national = national.slice(2);
    else if (national.startsWith("80")) national = national.slice(1);
    if (national === before) break;
    uaPrefix = true;
  }
  // ⚠️ Іноземний номер НЕ обрізаємо до дев'яти цифр: «+7 701 123 45 67» ставав «+380 77 011 23 45»
  // і проходив перевірку як український. Немає українського префікса й цифр забагато —
  // лишаємо як набрано, перевірка його відхилить. Набір із клавіатури це не зачіпає:
  // у полі вже стоїть «+380», і зайва цифра, як і раніше, просто відкидається.
  if (!uaPrefix && national.length > 9) return `+${digits}`;
  national = national.slice(0, 9);
  const groups = [
    national.slice(0, 2),
    national.slice(2, 5),
    national.slice(5, 7),
    national.slice(7, 9),
  ].filter(Boolean);
  return groups.length ? `+380 ${groups.join(" ")}` : "+380";
}

/**
 * Тримає курсор на місці в полі телефону, яке переформатовується на кожне натискання.
 *
 * ⚠️ НАВІЩО (24.11.2026). Після форматування React переписує значення поля, і курсор
 * стрибає в кінець. Хто виправляв цифру всередині номера, стирав одну, а нова лягала в
 * КІНЕЦЬ: виходив інший, але формально правильний номер — і замовлення з нього вже не
 * підтвердити, бо підтверджують дзвінком. Рахуємо цифри праворуч від курсора й після
 * перемальовування ставимо його так, щоб їх лишилось стільки ж.
 *
 * Викликати в onChange ДО зміни стану. Набір у кінець поля не зачіпає.
 */
export function keepPhoneCaret(el: HTMLInputElement): void {
  const pos = el.selectionStart;
  if (pos === null) return;
  const digitsAfter = el.value.slice(pos).replace(/\D/g, "").length;
  if (digitsAfter === 0) return;
  requestAnimationFrame(() => {
    const v = el.value;
    let p = v.length;
    for (let seen = 0; p > 0 && seen < digitsAfter; p--) if (/\d/.test(v[p - 1]!)) seen++;
    // Стаємо перед пробілом, а не після нього: інакше Backspace «залипає» на роздільнику.
    while (p > 0 && /\D/.test(v[p - 1]!)) p--;
    try {
      el.setSelectionRange(p, p);
    } catch {
      /* поле зникло або не підтримує виділення */
    }
  });
}

export function formatCardNumber(raw: string): string {
  return raw
    .replace(/\D/g, "")
    .slice(0, 16)
    .replace(/(.{4})/g, "$1 ")
    .trim();
}

export function formatCardExp(raw: string): string {
  const d = raw.replace(/\D/g, "").slice(0, 4);
  return d.length > 2 ? d.slice(0, 2) + "/" + d.slice(2) : d;
}
