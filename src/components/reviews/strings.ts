/** 1 відгук / 2 відгуки / 5 відгуків; 1 отзыв / 2 отзыва / 5 отзывов. */
export function plural(locale: Locale, n: number): string {
  const forms = locale === "ru" ? ["отзыв", "отзыва", "отзывов"] : ["відгук", "відгуки", "відгуків"];
  const m10 = n % 10;
  const m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return forms[0]!;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return forms[1]!;
  return forms[2]!;
}

/** 4.8 → «4,8» */
export const fmtAvg = (n: number) => n.toFixed(1).replace(".", ",");

/** 2026-10-21 → «21.10.2026» */
export const fmtDate = (iso: string) => {
  const [y, m, d] = iso.split("-");
  return `${d}.${m}.${y}`;
};
