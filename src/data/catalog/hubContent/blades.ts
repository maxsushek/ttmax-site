const t = (ua: string, ru: string) => ({ ua, ru });

const CLASS: Record<string, string> = {
  "off-plus": "OFF+",
  off: "OFF",
  "off-minus": "OFF−",
  "all-plus": "ALL+",
  all: "ALL",
  def: "DEF",
};

const FIBER: Record<string, string> = {
  alc: "ALC",
  "super-alc": "Super ALC",
  zlc: "ZLC",
  "super-zlc": "Super ZLC",
  zlf: "ZLF",
  t5000: "T5000",
  cnf: "CNF",
  caf: "CAF",
  carbon: "Карбон",
};

function material(p: CatalogProduct): { ua: string; ru: string } {
  const b = p.base;
  if (!b) return t("—", "—");
  if (b.surface === "wood" || !b.surface) {
    const n = Number(b.plies);
    return Number.isFinite(n) && n > 0 ? t(`Дерево, ${n} шарів`, `Дерево, ${n} слоёв`) : t("Дерево", "Дерево");
  }
  const fib = FIBER[b.surface] ?? b.surface;
  const pos = b.fiber === "inner" ? " · inner" : b.fiber === "outer" ? " · outer" : "";
  const plies = b.plies ? ` · ${b.plies}` : "";
  const name = fib === "Карбон" ? t("Карбон", "Карбон") : t(fib, fib);
  return t(`${name.ua}${pos}${plies}`, `${name.ru}${pos}${plies}`);
}

const num = (n: number | undefined) => (typeof n === "number" ? t(n.toFixed(1).replace(".", ","), n.toFixed(1).replace(".", ",")) : t("—", "—"));

/** Таблиця всіх основ хабу: спершу ті, що мають офіційні числа (за реакцією), далі решта за назвою. */
function bladeTable(classes: string[], heading: { ua: string; ru: string }): RichComparison {
  const items = getAllProducts().filter(
    (p) => p.base && classes.includes(p.base.bladeClass ?? "") && !isWithdrawn(p) && typeof getMinPrice(p) === "number",
  );
  items.sort((a, b) => {
    const ra = a.base?.reaction ?? -1;
    const rb = b.base?.reaction ?? -1;
    if (ra !== rb) return rb - ra;
    return (a.model ?? a.name.ua).localeCompare(b.model ?? b.name.ua);
  });
  const rows: RichRow[] = items.map((p) => ({
    href: `/${p.brandSlug}/${p.categorySlug}/${p.slug}`,
    cells: [
      t(p.model ?? p.name.ua, p.model ?? p.name.ru),
      t(CLASS[p.base?.bladeClass ?? ""] ?? "—", CLASS[p.base?.bladeClass ?? ""] ?? "—"),
      material(p),
      typeof p.base?.thicknessMm === "number" ? t(`${String(p.base.thicknessMm).replace(".", ",")} мм`, `${String(p.base.thicknessMm).replace(".", ",")} мм`) : t("—", "—"),
      num(p.base?.reaction),
      num(p.base?.vibration),
    ],
  }));
  return {
    heading,
    columns: [t("Модель", "Модель"), t("Клас", "Класс"), t("Матеріал", "Материал"), t("Товщина", "Толщина"), t("Реакція", "Реакция"), t("Вібрація", "Вибрация")],
    rows,
    note: t(
      "Реакція (базова швидкість) і вібрація (відчуття удару) — офіційні індекси Butterfly; вони є лише для частини моделей і порівнюються тільки між основами Butterfly. inner — волокно біля ядра, outer — під верхнім шпоном; 5+2 — пʼять шарів дерева й два шари волокна.",
      "Реакция (базовая скорость) и вибрация (ощущение удара) — официальные индексы Butterfly; они есть лишь для части моделей и сравниваются только между основаниями Butterfly. inner — волокно у ядра, outer — под верхним шпоном; 5+2 — пять слоёв дерева и два слоя волокна.",
    ),
  };
}

