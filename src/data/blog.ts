import type { Locale } from "@/i18n/config";
import type { AuthorSlug } from "@/data/authors";

type L = Record<Locale, string>;

/** Розділ статті (h2 + абзаци + опційна таблиця + контекстні лінки). id — якір для змісту/сітлінків. */
export type BlogSection = {
  /** Якір: /^[a-z0-9-]+$/, унікальний у межах статті. */
  id: string;
  h: L;
  p: Record<Locale, string[]>;
  table?: { columns: L[]; rows: L[][] };
  /**
   * Ілюстрація до розділу — схема або графік, а не фото товару (для фото є `rec`).
   *
   * ⚠️ src локалізований, бо підписи всередині SVG теж перекладені. Файли лежать
   * у /public/blog і ГЕНЕРУЮТЬСЯ скриптом із того самого каталогу, що й таблиці:
   * намальована руками картинка з зашитими числами розійшлася б із даними при
   * першій же зміні характеристик, і помітити це було б нікому.
   */
  image?: { src: L; alt: L; caption?: L };
  /** Опційна редакційна картка-рекомендація (фото товару + вердикт). Рендериться під абзацами, над таблицею/лінками. */
  rec?: BlogRec;
  /** Контекстні лінки на каталог у межах розділу (перелінковка). БЕЗ цін/кнопок. */
  links?: BlogLink[];
};

/** Часті запитання → FAQPage schema + видимий блок. */
export type BlogFaq = { q: L; a: L };

/** «Думка магазину» — врізка від першої особи автора. Тільки особистий досвід. */
export type BlogOpinion = { body: L };

/** Контекстний лінк на товар/категорію — БЕЗ цін і кнопок (щоб не канібалізувати каталог). */
export type BlogLink = { label: L; href: string };

/**
 * Редакційна картка-рекомендація в секції: реальне фото товару + вердикт тренера + лінк на money-картку.
 * СВІДОМО одинична (не масив) — тип фізично не дає зробити товарну сітку, що ламало б правило формату.
 * БЕЗ ціни, БЕЗ кнопки «Купити»: фото — ілюстрація до тексту, комерція живе тільки на картці товару.
 */
export type BlogRec = {
  /** Cloudinary publicId кадру (ttmax/product/{slug}/NN). Для унікальності в Google Images краще НЕ /00. */
  publicId: string;
  /** Назва товару з брендом. */
  name: L;
  /** 1 рядок вердикту тренера (джерело — колонка «Кому» порівняльної таблиці). */
  verdict: L;
  /** alt — свій на кожну локаль (кирилиця моделі), 5–15 слів, без слова «купити». */
  alt: L;
  /** Money-картка товару. */
  href: string;
};

export type BlogPost = {
  /** URL-сегмент: /{locale}/blog/<slug>. Регулярка: /^[a-z0-9-]{1,80}$/. */
  slug: string;
  /** H1 — питальний/інфо-формат (правило формату SEO-PLAN). */
  h1: L;
  /** <title> повний, з брендом. */
  metaTitle: L;
  metaDescription: L;
  /** Короткий опис для картки в списку + fallback og:description. */
  excerpt: L;
  /** ISO-дата (YYYY-MM-DD). Ставиться вручну, не new Date(). */
  datePublished: string;
  dateModified: string;
  author: AuthorSlug;
  /** Cloudinary publicId обкладинки (1200×630 для og). undefined — рендер без фото. */
  heroPublicId?: string;
  /** Фонове зображення для фірмової обкладинки (public-шлях). Поверх — лого й заголовок кодом. */
  coverSrc?: string;
  heroAlt: L;
  heroCaption?: L;
  /** Вступні абзаци (над змістом). */
  intro: Record<Locale, string[]>;
  sections: BlogSection[];
  opinion?: BlogOpinion;
  faq?: BlogFaq[];
  /** Посилання на офіційне першоджерело (напр. правила ITTF). Рендериться як зовнішній лінк. */
  officialSource?: { label: L; url: string };
  /**
   * Список джерел у кінці статті — для матеріалів, побудованих на дослідженні.
   *
   * ⚠️ Навіщо окремо від officialSource: той тримає ОДНЕ першоджерело, а дослідницька
   * стаття спирається на десятки — офіційні сторінки виробника, форуми гравців, правила.
   * Без переліку джерел текст із цифрами й цитатами читається як вигадка, а перевірити
   * його неможливо. Зовнішні лінки йдуть із rel="nofollow noopener".
   *
   * kind: "official" — виробник/федерація, "forum" — обговорення гравців, "review" — огляд.
   */
  sources?: { label: L; url: string; kind: "official" | "forum" | "review" }[];
  /** Контекстні лінки на товар (перелінковка → каталог). */
  relatedProducts?: BlogLink[];
  /** Слаги інших статей для блоку «Читайте також» (стаття → стаття). */
  relatedPosts?: string[];
  /**
   * Інтерактивний блок для залучення. playStyle — квіз стилю; racketPicker — підбір
   * ракетки за рівнем; tableSpace — підбір столу під простір; rubberPoll — опитування
   * «чим граєте ви» з живими результатами (єдиний із них зберігає дані в БД).
   */
  interactive?: "playStyle" | "racketPicker" | "tableSpace" | "rubberPoll";
  /** true → не рендериться на проді й не потрапляє в sitemap/список. */
  draft?: boolean;
};

