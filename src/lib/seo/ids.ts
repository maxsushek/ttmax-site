// src/lib/seo/ids.ts
// ПОСТІЙНІ @id вузлів розмітки. Єдине місце, де вони формуються.
//
// ⚠️ НАВІЩО. Без @id кожна сторінка оголошує НОВУ організацію: у нас 320+ сторінок
// описували 320 різних компаній із однаковими полями. Пошуковик і ШІ-асистент не мають
// підстав вважати їх однією. З постійним @id вузол на всіх сторінках — один і той самий,
// а властивості з різних сторінок склеюються в одну сутність.
//
// ⚠️ Ці рядки — ІДЕНТИФІКАТОРИ, а не адреси сторінок. Міняти їх не можна: для машини
// зміна @id означає «стара компанія зникла, зʼявилась нова», і накопичені звʼязки
// обнуляються. Домен береться з siteConfig.url (канонічний хост).
import { siteConfig } from "@/config/site";

/** Компанія (юридична сутність). */
export const orgId = () => `${siteConfig.url}/#org`;
/** Магазин як фізична точка (адреса, телефон). parentOrganization → orgId. */
export const businessId = () => `${siteConfig.url}/#business`;
/** Сайт як твір. */
export const websiteId = () => `${siteConfig.url}/#website`;
/** Логотип (ImageObject), щоб не повторювати URL у кожному publisher. */
export const logoId = () => `${siteConfig.url}/#logo`;
/** Товар: свій вузол на сторінці товару. */
export const productId = (url: string) => `${url}#product`;
/** Список товарів категорії. */
export const itemListId = (url: string) => `${url}#items`;

/** Посилання на вузол замість копії його полів. */
export const ref = (id: string) => ({ "@id": id });
