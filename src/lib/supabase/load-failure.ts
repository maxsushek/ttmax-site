// Єдина поведінка кешованих завантажувачів (фото, налаштування, ціни, описи), коли
// Supabase не відповів.

/**
 * ⚠️ ЗБІЙ БАЗИ НЕ МОЖНА ЗАПАМʼЯТОВУВАТИ. Кеші даних і сторінки живуть БЕЗ ТАЙМЕРА
 * (revalidate: false — пояснення в [...segments]/page.tsx): що в них потрапило, лежить до
 * наступної правки в адмінці або до деплою. Раніше завантажувачі при збої віддавали порожню
 * карту, і unstable_cache її зберігав — з таймером 3600 це лікувалось саме за годину, без
 * таймера було б назавжди: сайт без жодного фото (товари сховані й у noindex), ціни з коду
 * замість адмінки, контакти за замовчуванням.
 *
 * Тому — виняток. Він нічого не кешує: при перегенерації Vercel лишає попередню версію
 * сторінки, а сторінка, яку ще ніхто не відкривав, віддасть 500 і збереться на наступному
 * запиті. На білді виняток зупиняє деплой — червоний деплой помітний одразу, сайт без фото ні.
 *
 * Розрізняємо дві ситуації:
 *  • Supabase налаштований, але запит упав — це справжній збій: кидаємо завжди;
 *  • клієнта немає (не задано env) — на Vercel (VERCEL=1) це зламана конфігурація: кидаємо;
 *    локально це норма — збірка для перевірки розмітки без доступу до бази. Там фолбек і
 *    попередження, ламати цей інструмент не можна.
 */
export function noClient<T>(scope: string, fallback: T): T {
  if (process.env.VERCEL === "1") {
    throw new Error(`[${scope}] немає клієнта Supabase — перевір SUPABASE env у Vercel`);
  }
  console.warn(`[${scope}] немає клієнта Supabase — локально віддаю фолбек`);
  return fallback;
}

export function queryFailed(scope: string, reason: string): never {
  throw new Error(`[${scope}] запит до Supabase не вдався: ${reason}`);
}
