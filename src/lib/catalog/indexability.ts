// ⚠️ НАВІЩО ОКРЕМИЙ ФАЙЛ. Правило індексації живе у ДВОХ місцях одразу: routing.ts (звідки
// сторінка бере robots) і sitemap.ts (що ми подаємо Google). Коли вони розходяться, GSC
// сипле «Submitted URL marked noindex» — суперечливий сигнал: «проіндексуй» + «не індексуй».
// На комбо-ракетках це вже ловили руками; тепер обидва місця читають одну функцію, тож
// розійтись фізично не можуть.
import type { CatalogProduct } from "@/types/catalog";
import { getExpert } from "@/data/catalog/expert";

/**
 * Картку можна індексувати, якщо в неї є ВЛАСНИЙ зміст, якого немає на інших сторінках.
 *
 * Два винятки — обидва рахувались і підтверджені на даних, а не на думці:
 *
 * 1) КОМБО-РАКЕТКИ (95 шт.) — декартів добуток 5 основ × 19 комбінацій накладок. Кожна
 *    основа повторюється у 19 комбо, топ-накладка — у 25, а власного попиту в них немає
 *    (Ahrefs UA: 40/міс на всі 95 разом). Тобто це 95 конкурентів власним же money-карткам.
 *
 * 2) ЕКІПІРУВАННЯ БЕЗ ТЕКСТУ (296 із 297) — у gear-карток НЕМАЄ опису взагалі: лише назва,
 *    характеристики й ціна (перевірено проходом по каталогу — 0 слів у кожної). Попит на
 *    рівні моделі теж нульовий: Ahrefs ua дає «футболка butterfly» 10/міс, «кросівки
 *    butterfly» 10/міс — і це КАТЕГОРІЙНІ запити, їх ловить категорія; «чохол для ракетки»,
 *    «клей для накладок», «сумка butterfly» — 0. Тримати їх в індексі означає, що більшість
 *    URL сайту — сторінки без жодного слова тексту, а це вже оцінка якості САЙТУ, не сторінки.
 *
 * Виняток із винятку: якщо в товару є експертний блок або власні seoBlocks — текст є,
 * картка індексується. Так стіл (єдиний gear із 273 словами) лишається в індексі, і будь-яка
 * майбутня картка автоматично повертається, щойно їй напишуть змістовний текст.
 *
 * ВАЖЛИВО: це noindex, follow і лише для пошуковиків. Сторінки лишаються живими й продають
 * (рендер не читає index), у меню/лістингах вони на місці, а follow далі жене вагу
 * на накладки й основи.
 */
export function productIndexable(product: CatalogProduct): boolean {
  if (product.kind === "racket" && product.categorySlug === "rakety") return false;
  if (product.kind === "gear" && !getExpert(product.slug) && !product.seoBlocks?.length) {
    return false;
  }
  return true;
}
